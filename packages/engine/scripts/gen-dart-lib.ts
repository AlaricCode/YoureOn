/**
 * Pure helpers for `npm run gen:dart` (see gen-dart.ts).
 */
import { GLOBAL_CONSTANTS } from '../src/constants.js';

/** JSDoc text directly above `export const NAME` in constants.ts, flattened to one line. */
export function docComments(constantsSrc: string): Record<string, string> {
  const docs: Record<string, string> = {};
  const re = /\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*export const ([A-Z0-9_]+)\s*=/g;
  for (let m = re.exec(constantsSrc); m; m = re.exec(constantsSrc)) {
    const text = m[1]!
      .split('\n')
      .map((l) => l.replace(/^\s*\*\s?/, '').trim())
      .filter(Boolean)
      .join(' ');
    docs[m[2]!] = text;
  }
  return docs;
}

export function renderDartConstants(constantsSrc: string): string {
  const docs = docComments(constantsSrc);
  const lines = [
    '// GENERATED by `npm run gen:dart` (packages/engine/scripts/gen-dart.ts). Do not edit.',
    '// Global constants, CONTRACTS.md §0.5, mirrored from packages/engine/src/constants.ts.',
    '// ignore_for_file: constant_identifier_names',
    '',
  ];
  for (const [name, value] of Object.entries(GLOBAL_CONSTANTS)) {
    if (!Number.isSafeInteger(value)) throw new Error(`${name} is not a safe integer`);
    const doc = docs[name];
    if (doc) lines.push(`/// ${doc}`);
    lines.push(`const int ${name} = ${value};`);
  }
  return `${lines.join('\n')}\n`;
}

/** `const int NAME = VALUE;` declarations of a Dart file (underscore separators allowed). */
export function parseDartConstants(dart: string): Map<string, number> {
  const out = new Map<string, number>();
  const re = /^\s*const\s+int\s+([A-Z0-9_]+)\s*=\s*([0-9_]+)\s*;/gm;
  for (let m = re.exec(dart); m; m = re.exec(dart)) out.set(m[1]!, Number(m[2]!.replace(/_/g, '')));
  return out;
}

/** Differences between Dart declarations and the engine's §0.5 table (empty = consistent). */
export function diffDartConstants(dart: Map<string, number>): string[] {
  const problems: string[] = [];
  for (const [name, value] of Object.entries(GLOBAL_CONSTANTS)) {
    if (!dart.has(name)) problems.push(`missing ${name}`);
    else if (dart.get(name) !== value) problems.push(`${name} = ${dart.get(name)}, engine ${value}`);
  }
  for (const name of dart.keys()) if (!(name in GLOBAL_CONSTANTS)) problems.push(`extra ${name} (not in §0.5)`);
  return problems;
}
