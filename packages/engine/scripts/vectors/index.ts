/** All named vectors, in generation order. */
export function allVectors(): VectorJson[] {
  const vs: VectorJson[] = [...workedVectors(), ...primitiveVectors(), ...causeVectors(), ...pipelineVectors(), ...readbackVectors(), ...rejectionVectors()];
  const seen = new Set<string>();
  for (const v of vs) {
    const name = v.name as string;
    if (!/^[a-z0-9_]+$/.test(name)) throw new Error(`bad vector name ${name}`);
    if (seen.has(name)) throw new Error(`duplicate vector name ${name}`);
    seen.add(name);
  }
  assertReadbackCoverage(vs);
  const tags = new Set(vs.flatMap((v) => (v.covers as string[] | undefined) ?? []));
  const missing = REQUIRED_COVERAGE.filter((t) => !tags.has(t));
  if (missing.length) throw new Error(`§0.6 coverage items without a vector: ${missing.join(', ')}`);
  return vs;
}

export function serializeVector(v: VectorJson): string {
  return `${JSON.stringify(v, null, 2)}\n`;
}

/** Every file of `testvectors/`: `<name>.json` per vector, `fuzz.jsonl`, and `index.json`. */
export function buildFiles(opts: { fuzz?: boolean } = {}): Map<string, string> {
  const files = new Map<string, string>();
  const vs = allVectors();
  for (const v of vs) files.set(`${v.name as string}.json`, serializeVector(v));
  files.set('index.json', serializeVector(manifest(vs)));
  if (opts.fuzz !== false) files.set(FUZZ_FILE, buildFuzz());
  return files;
}

function buildFuzz(): string {
  return buildFuzzLines(FUZZ_SEED, FUZZ_CASES);
}

/** Manifest (no `expected`, so vector loaders skip it): names, descriptions and §0.6 coverage tags. */
function manifest(vs: VectorJson[]): VectorJson {
  const coverage: Record<string, string[]> = {};
  for (const v of vs) {
    for (const tag of (v.covers as string[] | undefined) ?? []) (coverage[tag] ??= []).push(v.name as string);
  }
  return {
    name: 'index',
    description: 'Generated by `npm run vectors` (packages/engine/scripts/vectors.ts). Do not edit by hand.',
    vectors: vs.map((v) => ({ name: v.name, description: v.description })),
    fuzz: { file: FUZZ_FILE, seed: FUZZ_SEED, cases: FUZZ_CASES },
    coverage: Object.fromEntries(Object.entries(coverage).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))),
  };
}
