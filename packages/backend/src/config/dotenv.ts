/**
 * Minimal `.env` support (§13): parse, merge into the process env (existing
 * variables win), and on first run generate the backend keys
 * (`FEE_PAYER_KEY`, `JUDGE_KEY_0..2`, plus `BIOMETRIC_KEY` and
 * `ELEVENLABS_TOOL_SECRET`) into `.env`, which is git-ignored and never
 * committed. `ORACLE_KEY` is left unset so it defaults to `FEE_PAYER_KEY`.
 */
import { randomBytes } from 'node:crypto';
import { appendFileSync, chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { generateKeypair, secretToBase58 } from '../crypto/keys.js';
import type { Env } from './load.js';
import { GENERATED_HEX_VARS, GENERATED_KEY_VARS } from './schema.js';

const LINE_RE = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)?\s*$/;

/** Parses dotenv text: `KEY=value`, `# comments`, single/double quotes, `export` prefix. */
export function parseDotenv(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line === '' || line.startsWith('#')) continue;
    const m = LINE_RE.exec(line);
    if (!m) continue;
    let v = (m[2] ?? '').trim();
    if ((v.startsWith('"') && v.endsWith('"') && v.length >= 2) || (v.startsWith("'") && v.endsWith("'") && v.length >= 2)) {
      const dq = v.startsWith('"');
      v = v.slice(1, -1);
      if (dq) v = v.replace(/\\n/g, '\n').replace(/\\"/g, '"').replace(/\\\\/g, '\\');
    } else {
      const hash = v.indexOf(' #');
      if (hash >= 0) v = v.slice(0, hash).trim();
    }
    out[m[1]!] = v;
  }
  return out;
}

/** Walks up from `start` to the npm workspace root (package.json with "workspaces"). */
export function findRepoRoot(start: string = process.cwd()): string {
  let dir = resolve(start);
  for (;;) {
    const pj = join(dir, 'package.json');
    if (existsSync(pj)) {
      try {
        const j = JSON.parse(readFileSync(pj, 'utf8')) as { workspaces?: unknown };
        if (j.workspaces) return dir;
      } catch {
        /* keep walking */
      }
    }
    const up = dirname(dir);
    if (up === dir) return resolve(start);
    dir = up;
  }
}

export function defaultEnvPath(): string {
  return join(findRepoRoot(), '.env');
}

export interface EnsureEnvResult {
  path: string;
  /** names of variables generated into the file by this call */
  generated: string[];
  /** merged env (file values under `base`, which wins) */
  env: Env;
}

/** Generates the value for a generated variable. */
function generate(name: string): string {
  if ((GENERATED_KEY_VARS as readonly string[]).includes(name)) return secretToBase58(generateKeypair());
  if ((GENERATED_HEX_VARS as readonly string[]).includes(name)) return randomBytes(32).toString('hex');
  if (name === 'ELEVENLABS_TOOL_SECRET') return randomBytes(24).toString('base64url');
  throw new Error(`no generator for ${name}`);
}

export const GENERATED_VARS: readonly string[] = [...GENERATED_KEY_VARS, ...GENERATED_HEX_VARS, 'ELEVENLABS_TOOL_SECRET'];

/**
 * Reads `.env` (creating it if absent), appends any missing generated keys,
 * and returns the merged env. Non-empty variables in `base` (the real
 * process env) win over the file and are never generated.
 */
export function ensureEnvFile(path: string = defaultEnvPath(), base: Env = process.env): EnsureEnvResult {
  const existed = existsSync(path);
  const fileVars = existed ? parseDotenv(readFileSync(path, 'utf8')) : {};
  const missing = GENERATED_VARS.filter((k) => !nonEmpty(base[k]) && !nonEmpty(fileVars[k]));
  if (missing.length > 0) {
    const lines = missing.map((k) => {
      const v = generate(k);
      fileVars[k] = v;
      return `${k}=${v}`;
    });
    const header = existed
      ? `\n# Generated by @verdict/backend on ${new Date().toISOString()}\n`
      : `# Verdict backend secrets. Generated on first run. NEVER commit this file.\n# See .env.example for every option.\n`;
    if (existed) appendFileSync(path, header + lines.join('\n') + '\n', { mode: 0o600 });
    else writeFileSync(path, header + lines.join('\n') + '\n', { mode: 0o600 });
    try {
      chmodSync(path, 0o600);
    } catch {
      /* best effort (e.g. non-POSIX fs) */
    }
  }
  const env: Env = { ...fileVars };
  for (const [k, v] of Object.entries(base)) if (v !== undefined && (nonEmpty(v) || env[k] === undefined)) env[k] = v;
  return { path, generated: missing, env };
}

function nonEmpty(v: string | undefined): boolean {
  return v !== undefined && v.trim() !== '';
}
