//! Actor-bound scenario (identity checkpoints) used by the biometric tests and the proof fixture.
#![allow(dead_code)]

use super::flow::*;
use super::payload::*;
use super::*;

pub const CHECKPOINT_FRAME: u32 = 12;

/// `exists present(person P0)` actor-bound; true ⇒ side 0 (creator) wins, else side 1.
pub fn actor_flow(env: Env) -> Flow {
    let users = default_users(2);
    let keys: Vec<Pubkey> = users.iter().map(|u| u.pubkey()).collect();
    let stakes = vec![STAKE; 2];
    let program_bin = ProgramB {
        kind: 0,
        time_limit_s: 60,
        participants: keys.clone(),
        stakes: stakes.clone(),
        side_b_mask: 0b10,
        entities: vec![(EK_PERSON, 0)],
        legs: vec![LegB::exists(1, present(0)).actor()],
        if_true: 0,
        else_side: 1,
        cond: cond_leg(1),
    }
    .encode();
    let tracks = tracks_bin(FLAGS_OK, &[(0, 0, 0)], &[(0, 40)], |_, f| if f >= CHECKPOINT_FRAME { person_at(5000, 8000) } else { ABSENT });
    let spec = Spec {
        nonce: 7,
        flags: FLAG_ACTOR_BOUND,
        stakes,
        stake_each: STAKE,
        side_b_mask: 0b10,
        time_limit_s: 60,
        acceptance: [0x42; 32],
        program_bin,
        calibration_bin: calibration(&[]),
        tracks_bin: tracks,
    };
    Flow::with(env, users, spec)
}

pub fn init_profile_ix(payer: &Pubkey, wallet: &Pubkey, face: [u8; 32], voice: [u8; 32], name: &str) -> Instruction {
    ix(
        verdict::instruction::InitProfile { face_commit: face, voice_commit: voice, display_name: name.to_string() },
        verdict::accounts::InitProfile {
            payer: *payer,
            wallet: *wallet,
            profile: profile_pda(wallet),
            system_program: solana_sdk::system_program::ID,
        },
        &[],
    )
}

pub struct Proof {
    pub participant: u8,
    pub modality: u8,
    pub frame: u32,
    pub tau_bps: u16,
    pub a: [u8; 64],
    pub b: [u8; 128],
    pub c: [u8; 64],
}

impl Proof {
    pub fn mock(participant: u8, frame: u32) -> Proof {
        Proof { participant, modality: 0, frame, tau_bps: TAU_FACE_BPS, a: [1; 64], b: [0; 128], c: [0; 64] }
    }
}

pub fn verify_ix(f: &Flow, wallet: &Pubkey, p: &Proof) -> Instruction {
    ix(
        verdict::instruction::VerifyBiometricProof {
            participant: p.participant,
            modality: p.modality,
            frame: p.frame,
            tau_bps: p.tau_bps,
            proof_a: p.a,
            proof_b: p.b,
            proof_c: p.c,
        },
        verdict::accounts::VerifyBiometricProof { oracle: f.env.oracle.pubkey(), bet: f.bet, profile: profile_pda(wallet) },
        &[],
    )
}

pub fn try_verify(f: &mut Flow, wallet: &Pubkey, p: &Proof) -> TxResult {
    let ixn = verify_ix(f, wallet, p);
    let o = f.env.oracle.insecure_clone();
    f.env.send_with(&[ixn], &[&o], Some(300_000))
}

/// Real Groth16 proof fixture (generated by tests/fixtures/gen_biometric_fixture.mjs).
pub struct Fixture {
    pub bet: Pubkey,
    pub evidence_root: [u8; 32],
    pub commitment: [u8; 32],
    pub proof: Proof,
}

pub fn load_fixture() -> Option<Fixture> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/biometric_proof.json");
    let text = std::fs::read_to_string(path).ok()?;
    let v: serde_json::Value = serde_json::from_str(&text).ok()?;
    let h = |k: &str| hex(v[k].as_str().unwrap_or_else(|| panic!("fixture field {k}")));
    let arr32 = |k: &str| -> [u8; 32] { h(k).try_into().unwrap() };
    Some(Fixture {
        bet: Pubkey::new_from_array(arr32("bet")),
        evidence_root: arr32("evidence_root"),
        commitment: arr32("commitment"),
        proof: Proof {
            participant: v["participant"].as_u64().unwrap() as u8,
            modality: v["modality"].as_u64().unwrap() as u8,
            frame: v["frame"].as_u64().unwrap() as u32,
            tau_bps: v["tau_bps"].as_u64().unwrap() as u16,
            a: h("proof_a").try_into().unwrap(),
            b: h("proof_b").try_into().unwrap(),
            c: h("proof_c").try_into().unwrap(),
        },
    })
}
