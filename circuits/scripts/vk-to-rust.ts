// Converts a snarkjs Groth16 verification_key.json (BN254) into a groth16-solana
// `Groth16Verifyingkey` Rust constant (CONTRACTS.md §8.6).
//
// Encoding (big-endian, 32 bytes per base-field coordinate):
//   G1 = x ‖ y                       (64 bytes)
//   G2 = x.c1 ‖ x.c0 ‖ y.c1 ‖ y.c0   (128 bytes; snarkjs stores [c0, c1])
//
// Usage: node scripts/vk-to-rust.ts [verification_key.json] [out.rs]
// Defaults: build/verification_key.json -> build/vk.rs
// Uses only erasable TypeScript syntax, so Node >= 22.6 runs it directly (type stripping).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

type G1 = [string, string, string];
type G2 = [[string, string], [string, string], [string, string]];
interface SnarkjsVk {
  protocol: string;
  curve: string;
  nPublic: number;
  vk_alpha_1: G1;
  vk_beta_2: G2;
  vk_gamma_2: G2;
  vk_delta_2: G2;
  IC: G1[];
}

export const BN254_P =
  21888242871839275222246405745257275088696311157297823662689037894645226208583n;

export function fieldToBytesBE(dec: string): number[] {
  let v = BigInt(dec);
  if (v < 0n || v >= BN254_P) throw new Error(`coordinate out of range: ${dec}`);
  const out: number[] = new Array(32).fill(0);
  for (let i = 31; i >= 0; i--) {
    out[i] = Number(v & 0xffn);
    v >>= 8n;
  }
  return out;
}

function assertAffine(z: string, what: string): void {
  if (z !== "1") throw new Error(`${what}: expected affine point (z = 1), got z = ${z}`);
}

export function g1Bytes(p: G1, what: string): number[] {
  assertAffine(p[2], what);
  return [...fieldToBytesBE(p[0]), ...fieldToBytesBE(p[1])];
}

export function g2Bytes(p: G2, what: string): number[] {
  if (p[2][0] !== "1" || p[2][1] !== "0") throw new Error(`${what}: expected affine G2 point`);
  return [
    ...fieldToBytesBE(p[0][1]),
    ...fieldToBytesBE(p[0][0]),
    ...fieldToBytesBE(p[1][1]),
    ...fieldToBytesBE(p[1][0]),
  ];
}

function fmtBytes(bytes: number[], indent: string): string {
  const lines: string[] = [];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push(indent + bytes.slice(i, i + 16).map((b) => `${b}`).join(", ") + ",");
  }
  return lines.join("\n");
}

export function vkToRust(vk: SnarkjsVk): string {
  if (vk.protocol !== "groth16") throw new Error(`unsupported protocol ${vk.protocol}`);
  if (vk.curve !== "bn128") throw new Error(`unsupported curve ${vk.curve}`);
  if (vk.IC.length !== vk.nPublic + 1) throw new Error("IC length must be nPublic + 1");

  const g2 = (name: string, p: G2) =>
    `    ${name}: [\n${fmtBytes(g2Bytes(p, name), "        ")}\n    ],`;
  const ic = vk.IC.map(
    (p, i) => `        [\n${fmtBytes(g1Bytes(p, `IC[${i}]`), "            ")}\n        ],`,
  ).join("\n");

  return `// @generated by circuits/scripts/vk-to-rust.ts from circuits/build/verification_key.json.
// DO NOT EDIT. Regenerate with \`circuits/scripts/setup.sh\` (fixed dev beacon, CONTRACTS.md §8.6).
// Circuit: circuits/biometric_match.circom, BiometricMatch(192), ${vk.nPublic} public inputs.

use groth16_solana::groth16::Groth16Verifyingkey;

pub const NR_PUBLIC_INPUTS: usize = ${vk.nPublic};

pub const VK: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},
    vk_alpha_g1: [
${fmtBytes(g1Bytes(vk.vk_alpha_1, "alpha"), "        ")}
    ],
${g2("vk_beta_g2", vk.vk_beta_2)}
${g2("vk_gamme_g2", vk.vk_gamma_2)}
${g2("vk_delta_g2", vk.vk_delta_2)}
    vk_ic: &[
${ic}
    ],
};
`;
}

function main(argv: string[]): void {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const input = argv[0] ?? resolve(root, "build/verification_key.json");
  const output = argv[1] ?? resolve(root, "build/vk.rs");
  const vk = JSON.parse(readFileSync(input, "utf8")) as SnarkjsVk;
  writeFileSync(output, vkToRust(vk));
  console.log(`wrote ${output} (${vk.nPublic} public inputs)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
